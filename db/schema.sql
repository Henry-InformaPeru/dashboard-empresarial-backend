-- Esquema de Dashboard Empresarial en PostgreSQL (equivale a las tablas que antes vivian en SQL Server).
-- Se puede correr varias veces: crea solo lo que falta y no toca datos.
--   psql -v ON_ERROR_STOP=1 -f db/schema.sql
-- Los nombres de esquemas, tablas y columnas son los que usan las entidades de src/ (con las mismas mayusculas).

CREATE SCHEMA IF NOT EXISTS seguridad;
CREATE SCHEMA IF NOT EXISTS reportes;
CREATE SCHEMA IF NOT EXISTS comercial;

CREATE TABLE IF NOT EXISTS seguridad."Roles" (
  id_rol      int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre      varchar(50)  NOT NULL,
  descripcion varchar(255)
);

-- Los roles que usa el codigo: 1 = administrador de Sulotec/Informa, 2 = cliente (pertenece a una empresa)
INSERT INTO seguridad."Roles" (id_rol, nombre, descripcion)
OVERRIDING SYSTEM VALUE
VALUES (1, 'ADMIN', 'Administrador general'), (2, 'CLIENT', 'Usuario de una empresa cliente')
ON CONFLICT (id_rol) DO NOTHING;

CREATE TABLE IF NOT EXISTS comercial."Empresas" (
  id_empresa     int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre         varchar(200) NOT NULL,
  ruc            varchar(11),
  estado         varchar(20)  NOT NULL,
  fecha_creacion timestamptz  NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS seguridad."Usuarios" (
  id_usuario      int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa      int,
  id_rol          int,
  username        varchar(150) NOT NULL,
  email           varchar(255),
  nombre_completo varchar(255),
  password_hash   varchar(255) NOT NULL,
  estado          varchar(20)  NOT NULL DEFAULT 'ACTIVO',
  fecha_creacion  timestamptz  NOT NULL DEFAULT now()
);
-- SQL Server no distinguia mayusculas en el usuario; aqui el indice unico tampoco
CREATE UNIQUE INDEX IF NOT EXISTS "UX_Usuarios_username" ON seguridad."Usuarios" (LOWER(username));

CREATE TABLE IF NOT EXISTS reportes."Dashboards" (
  id_dashboard   int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo         varchar(50)  NOT NULL,
  nombre         varchar(255) NOT NULL,
  descripcion    varchar(500),
  estado         varchar(20)  NOT NULL,
  url_powerbi    varchar(2048),
  fecha_creacion timestamptz  NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS reportes."DashboardPeriodos" (
  id_dashboard_periodo int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_dashboard         int           NOT NULL,
  periodo              char(6)       NOT NULL,
  url_powerbi          varchar(2048),
  url_mega             varchar(2048),
  fecha_creacion       timestamptz   NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS "IX_DashboardPeriodos_dashboard_periodo" ON reportes."DashboardPeriodos" (id_dashboard, periodo);

CREATE TABLE IF NOT EXISTS comercial."EmpresaDashboards" (
  id_empresa_dashboard int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa           int         NOT NULL,
  id_dashboard         int         NOT NULL,
  fecha_asignacion     timestamptz NOT NULL DEFAULT now(),
  estado               varchar(20) NOT NULL DEFAULT 'ACTIVO',
  fecha_desactivacion  timestamptz
);
-- El codigo responde "ya tiene una asignacion" cuando salta este indice
CREATE UNIQUE INDEX IF NOT EXISTS "UX_EmpresaDashboards_empresa_dashboard" ON comercial."EmpresaDashboards" (id_empresa, id_dashboard);

-- Llaves foraneas. Van NOT VALID a proposito: no revisan las filas que ya existen (datos copiados de SQL Server),
-- pero si exigen que todo lo nuevo sea coherente.
DO $$
DECLARE
  fk record;
BEGIN
  FOR fk IN SELECT * FROM (VALUES
    ('seguridad."Usuarios"',          'FK_Usuarios_Empresas',            'FOREIGN KEY (id_empresa)   REFERENCES comercial."Empresas" (id_empresa)'),
    ('seguridad."Usuarios"',          'FK_Usuarios_Roles',               'FOREIGN KEY (id_rol)       REFERENCES seguridad."Roles" (id_rol)'),
    ('reportes."DashboardPeriodos"',  'FK_DashboardPeriodos_Dashboards', 'FOREIGN KEY (id_dashboard) REFERENCES reportes."Dashboards" (id_dashboard)'),
    ('comercial."EmpresaDashboards"', 'FK_EmpresaDashboards_Empresas',   'FOREIGN KEY (id_empresa)   REFERENCES comercial."Empresas" (id_empresa)'),
    ('comercial."EmpresaDashboards"', 'FK_EmpresaDashboards_Dashboards', 'FOREIGN KEY (id_dashboard) REFERENCES reportes."Dashboards" (id_dashboard)')
  ) AS t(tabla, nombre, definicion)
  LOOP
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = fk.nombre) THEN
      EXECUTE format('ALTER TABLE %s ADD CONSTRAINT %I %s NOT VALID', fk.tabla, fk.nombre, fk.definicion);
    END IF;
  END LOOP;
END $$;

-- Cambios para las bases que ya existian (las tablas de arriba solo se crean si faltan). Todo se puede repetir sin problema.
-- El vinculo de Power BI pasa a ser del reporte (Dashboards.url_powerbi) y el periodo queda solo para la descarga de MEGA.
-- Un periodo puede seguir llevando un vinculo propio (si ese mes usa otro reporte); sin el, usa el del reporte.
ALTER TABLE reportes."Dashboards" ADD COLUMN IF NOT EXISTS url_powerbi varchar(2048);
ALTER TABLE reportes."DashboardPeriodos" ALTER COLUMN url_powerbi DROP NOT NULL;
-- Los reportes que ya tenian periodos reciben el vinculo de su periodo mas reciente (solo si aun no tienen uno).
-- Si ese periodo se guardo con el HTML completo del iframe, se toma solo su src.
UPDATE reportes."Dashboards" d
   SET url_powerbi = (SELECT COALESCE(substring(p.url_powerbi from 'src="([^"]+)"'), p.url_powerbi)
                        FROM reportes."DashboardPeriodos" p
                       WHERE p.id_dashboard = d.id_dashboard AND p.url_powerbi IS NOT NULL AND p.url_powerbi <> ''
                       ORDER BY p.periodo DESC, p.id_dashboard_periodo DESC
                       LIMIT 1)
 WHERE d.url_powerbi IS NULL;
